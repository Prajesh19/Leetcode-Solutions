class Solution {
    public List<Integer> findDisappearedNumbers(int[] nums) {
        // 1. Mark each existing number's corresponding index as negative
        for (int i = 0; i < nums.length; i++) {
            int index = Math.abs(nums[i]) - 1;
            if (nums[index] > 0) {
                nums[index] = -nums[index];
            }
        }
        // 2. Any index that remains positive was never visited -> (i + 1) is missing
        List<Integer> list = new ArrayList<>();
        for (int i = 0; i < nums.length; i++) {
            if (nums[i] > 0) {
                list.add(i + 1);
            }
        }
        return list;
    }
}